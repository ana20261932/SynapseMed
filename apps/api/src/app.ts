import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';

import { errorHandler } from './middleware/errorHandler';
import { notFound } from './middleware/notFound';
import authRoutes from './routes/auth.routes';
import practiceRoutes from './routes/practice.routes';
import membershipRoutes from './routes/membership.routes';
import patientRoutes from './routes/patient.routes';
import appointmentRoutes from './routes/appointment.routes';
import clinicalRoutes from './routes/clinical.routes';
import billingRoutes from './routes/billing.routes';
import switchRoutes from './routes/switch.routes';
import inventoryRoutes from './routes/inventory.routes';
import subscriptionRoutes from './routes/subscription.routes';
import paymentRoutes from './routes/payment.routes';
import documentRoutes from './routes/document.routes';
import dentalRoutes from './routes/dental.routes';
import radiologyRoutes from './routes/radiology.routes';
import psychiatryRoutes from './routes/psychiatry.routes';
import alliedHealthRoutes from './routes/alliedHealth.routes';
import cloudantRoutes from './routes/cloudant.routes';
import aiRoutes from './routes/ai.routes';
import extensionsRoutes from './routes/extensions.routes';
import transcriptionRoutes from './routes/transcription.routes';
import assistantRoutes from './routes/assistant.routes';
import storageRoutes from './routes/storage.routes';
import timelineRoutes from './routes/timeline.routes';
import erpnextRoutes from './routes/erpnext.routes';
import automationRoutes from './routes/automation.routes';
import settingsRoutes from './routes/settings.routes';
import healthRoutes from './routes/health.routes';
import platformRoutes from './routes/platform.routes';

const app = express();

app.use(helmet());
app.use(cors({ origin: process.env.APP_BASE_URL ?? 'http://localhost:3000', credentials: true }));
app.use(express.json({ limit: '1mb' }));
app.use(express.urlencoded({ extended: true }));
app.use(cookieParser());
if (process.env.NODE_ENV !== 'test') app.use(morgan('combined'));

const limiter = rateLimit({ windowMs: 15 * 60 * 1000, max: 200, standardHeaders: true, legacyHeaders: false });
app.use('/api/', limiter);

app.use('/api/v1/health', healthRoutes);
app.use('/api/v1/auth', authRoutes);
app.use('/api/v1/practices', practiceRoutes);
app.use('/api/v1/practices/:practiceId/memberships', membershipRoutes);
app.use('/api/v1/practices/:practiceId/patients', patientRoutes);
app.use('/api/v1/practices/:practiceId/appointments', appointmentRoutes);
app.use('/api/v1/practices/:practiceId/clinical', clinicalRoutes);
app.use('/api/v1/practices/:practiceId/billing', billingRoutes);
app.use('/api/v1/practices/:practiceId/switch', switchRoutes);
app.use('/api/v1/practices/:practiceId/inventory', inventoryRoutes);
app.use('/api/v1/practices/:practiceId/subscriptions', subscriptionRoutes);
app.use('/api/v1/practices/:practiceId/payments', paymentRoutes);
app.use('/api/v1/practices/:practiceId/documents', documentRoutes);
app.use('/api/v1/practices/:practiceId/dental', dentalRoutes);
app.use('/api/v1/practices/:practiceId/radiology', radiologyRoutes);
app.use('/api/v1/practices/:practiceId/psychiatry', psychiatryRoutes);
app.use('/api/v1/practices/:practiceId/allied-health', alliedHealthRoutes);
app.use('/api/v1/practices/:practiceId/ai', aiRoutes);
app.use('/api/v1/extensions', extensionsRoutes);
app.use('/api/v1/practices/:practiceId/extensions', extensionsRoutes);
app.use('/api/v1/practices/:practiceId/transcription', transcriptionRoutes);
app.use('/api/v1/practices/:practiceId', timelineRoutes);
app.use('/api/v1/practices/:practiceId/erpnext', erpnextRoutes);
app.use('/api/v1/practices/:practiceId/automation', automationRoutes);
app.use('/api/v1/practices/:practiceId/settings', settingsRoutes);
app.use('/api/v1/practices/:practiceId/assistant', assistantRoutes);
app.use('/api/v1/practices/:practiceId/storage', storageRoutes);
app.use('/api/v1/practices/:practiceId/cloudant', cloudantRoutes);
app.use('/api/v1/platform', platformRoutes);
app.use('/api/v1/practices/:practiceId/platform', platformRoutes);

app.use(notFound);
app.use(errorHandler);

export default app;
